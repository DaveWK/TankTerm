_tankTerm() {
    local i cur prev opts cmd
    COMPREPLY=()
    if [[ "${BASH_VERSINFO[0]}" -ge 4 ]]; then
        cur="$2"
    else
        cur="${COMP_WORDS[COMP_CWORD]}"
    fi
    prev="$3"
    cmd=""
    opts=""

    for i in "${COMP_WORDS[@]:0:COMP_CWORD}"
    do
        case "${cmd},${i}" in
            ",$1")
                cmd="tankTerm"
                ;;
            tankTerm,help)
                cmd="tankTerm__subcmd__help"
                ;;
            tankTerm,migrate)
                cmd="tankTerm__subcmd__migrate"
                ;;
            tankTerm,msg)
                cmd="tankTerm__subcmd__msg"
                ;;
            tankTerm__subcmd__help,help)
                cmd="tankTerm__subcmd__help__subcmd__help"
                ;;
            tankTerm__subcmd__help,migrate)
                cmd="tankTerm__subcmd__help__subcmd__migrate"
                ;;
            tankTerm__subcmd__help,msg)
                cmd="tankTerm__subcmd__help__subcmd__msg"
                ;;
            tankTerm__subcmd__help__subcmd__msg,config)
                cmd="tankTerm__subcmd__help__subcmd__msg__subcmd__config"
                ;;
            tankTerm__subcmd__help__subcmd__msg,create-window)
                cmd="tankTerm__subcmd__help__subcmd__msg__subcmd__create__subcmd__window"
                ;;
            tankTerm__subcmd__help__subcmd__msg,get-config)
                cmd="tankTerm__subcmd__help__subcmd__msg__subcmd__get__subcmd__config"
                ;;
            tankTerm__subcmd__msg,config)
                cmd="tankTerm__subcmd__msg__subcmd__config"
                ;;
            tankTerm__subcmd__msg,create-window)
                cmd="tankTerm__subcmd__msg__subcmd__create__subcmd__window"
                ;;
            tankTerm__subcmd__msg,get-config)
                cmd="tankTerm__subcmd__msg__subcmd__get__subcmd__config"
                ;;
            tankTerm__subcmd__msg,help)
                cmd="tankTerm__subcmd__msg__subcmd__help"
                ;;
            tankTerm__subcmd__msg__subcmd__help,config)
                cmd="tankTerm__subcmd__msg__subcmd__help__subcmd__config"
                ;;
            tankTerm__subcmd__msg__subcmd__help,create-window)
                cmd="tankTerm__subcmd__msg__subcmd__help__subcmd__create__subcmd__window"
                ;;
            tankTerm__subcmd__msg__subcmd__help,get-config)
                cmd="tankTerm__subcmd__msg__subcmd__help__subcmd__get__subcmd__config"
                ;;
            tankTerm__subcmd__msg__subcmd__help,help)
                cmd="tankTerm__subcmd__msg__subcmd__help__subcmd__help"
                ;;
            *)
                ;;
        esac
    done

    case "${cmd}" in
        tankTerm)
            opts="-q -v -e -T -o -h -V --config-file --socket --daemon --theme --working-directory --hold --command --title --class --option --help --version msg migrate help"
            if [[ ${cur} == -* || ${COMP_CWORD} -eq 1 ]] ; then
                COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
                return 0
            fi
            case "${prev}" in
                --config-file)
                    local oldifs
                    if [ -n "${IFS+x}" ]; then
                        oldifs="$IFS"
                    fi
                    IFS=$'\n'
                    COMPREPLY=($(compgen -f "${cur}"))
                    if [ -n "${oldifs+x}" ]; then
                        IFS="$oldifs"
                    fi
                    if [[ "${BASH_VERSINFO[0]}" -ge 4 ]]; then
                        compopt -o filenames
                    fi
                    return 0
                    ;;
                --socket)
                    local oldifs
                    if [ -n "${IFS+x}" ]; then
                        oldifs="$IFS"
                    fi
                    IFS=$'\n'
                    COMPREPLY=($(compgen -f "${cur}"))
                    if [ -n "${oldifs+x}" ]; then
                        IFS="$oldifs"
                    fi
                    if [[ "${BASH_VERSINFO[0]}" -ge 4 ]]; then
                        compopt -o filenames
                    fi
                    return 0
                    ;;
                --theme)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                --working-directory)
                    local oldifs
                    if [ -n "${IFS+x}" ]; then
                        oldifs="$IFS"
                    fi
                    IFS=$'\n'
                    COMPREPLY=($(compgen -f "${cur}"))
                    if [ -n "${oldifs+x}" ]; then
                        IFS="$oldifs"
                    fi
                    if [[ "${BASH_VERSINFO[0]}" -ge 4 ]]; then
                        compopt -o filenames
                    fi
                    return 0
                    ;;
                --command)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                -e)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                --title)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                -T)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                --class)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                --option)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                -o)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                *)
                    COMPREPLY=()
                    ;;
            esac
            COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
            return 0
            ;;
        tankTerm__subcmd__help)
            opts="msg migrate help"
            if [[ ${cur} == -* || ${COMP_CWORD} -eq 2 ]] ; then
                COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
                return 0
            fi
            case "${prev}" in
                *)
                    COMPREPLY=()
                    ;;
            esac
            COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
            return 0
            ;;
        tankTerm__subcmd__help__subcmd__help)
            opts=""
            if [[ ${cur} == -* || ${COMP_CWORD} -eq 3 ]] ; then
                COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
                return 0
            fi
            case "${prev}" in
                *)
                    COMPREPLY=()
                    ;;
            esac
            COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
            return 0
            ;;
        tankTerm__subcmd__help__subcmd__migrate)
            opts=""
            if [[ ${cur} == -* || ${COMP_CWORD} -eq 3 ]] ; then
                COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
                return 0
            fi
